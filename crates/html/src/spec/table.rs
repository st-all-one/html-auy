/// Elemento pelo nome do `html!` (`None` = desconhecido).
#[must_use]
pub fn element(name: &str) -> Option<&'static Element> {
    ELEMENTS.iter().find(|candidate| candidate.name == name)
}

/// Escopo declarado da invariante.
#[must_use]
pub fn invariant_scope(name: &str) -> Option<Scope> {
    INVARIANT_SCOPES
        .iter()
        .find(|(candidate, _)| *candidate == name)
        .map(|(_, scope)| *scope)
}

/// Valores literais de `(elemento, atributo)`: exato primeiro, default depois.
#[must_use]
pub fn attr_values(element: &str, attr: &str) -> Option<&'static AttrValues> {
    let exact = ATTR_VALUES
        .iter()
        .find(|entry| entry.element == element && entry.attr == attr);
    exact.or_else(|| {
        ATTR_VALUES
            .iter()
            .find(|entry| entry.element.is_empty() && entry.attr == attr)
    })
}

/// Atributos extras aceitos pelo tipo de `input`.
#[must_use]
pub fn input_attrs(input_type: &str) -> Option<&'static [&'static str]> {
    INPUT_ATTRS
        .iter()
        .find(|(candidate, _)| *candidate == input_type)
        .map(|(_, attrs)| *attrs)
}
