/// Escopo de uma invariante: quem cobra a regra (docs/04 §4.0).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Scope {
    /// Decidido dentro de um bloco `html!`: erro de compilação com span.
    Block,
    /// Decidido pelo construtor do crate (`Page`, `Form`): não compila sem o dado.
    Type,
    /// Só o HTML final responde (`audit` sobre a saída).
    Output,
}

/// Quem emite o elemento: o shell (`Page`) ou um componente do crate (`Form`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Only {
    /// `html!` recusa: só o `Page` emite.
    Shell,
    /// `html!` recusa: só o primitivo do crate emite.
    Component,
}

/// Tipo do valor de um atributo global ou `aria-*`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum NameKind {
    /// Obrigatório no elemento.
    Required,
    /// Permitido, não obrigatório.
    Optional,
    /// Não se aplica ao elemento.
    None,
    /// Atributo global (aceito em qualquer elemento).
    Attr,
}

/// Tipo do valor aceito: enum fechado ou gramática.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ValueKind {
    /// Lista fechada de literais.
    Enum,
    /// Identificador (`Id`).
    Id,
    /// Referência a um id (uma só).
    IdRef,
    /// Lista de referências a id.
    IdRefList,
    /// Texto livre, escapado.
    Text,
    /// Lista de tokens separados por espaço.
    Tokens,
    /// `data-*`: o consumidor declara.
    Declared,
    /// Etiqueta BCP-47 (`Lang`).
    Bcp47,
    /// Tipo MIME (`tipo/subtipo`).
    Mime,
    /// Atributo de presença (booleano).
    Presence,
}

/// Um elemento do vocabulário.
#[derive(Debug, PartialEq, Eq)]
pub struct Element {
    /// Nome no `html!`.
    pub name: &'static str,
    /// Tag emitida (difere do nome em `svg_title` e `media_source`).
    pub tag: &'static str,
    /// Categorias de conteúdo-modelo a que o elemento pertence.
    pub categories: &'static [&'static str],
    /// Atributos obrigatórios (implicitamente permitidos).
    pub required: &'static [&'static str],
    /// Allowlist adicional.
    pub allowed: &'static [&'static str],
    /// Ordem de emissão quando difere de `required ++ allowed ++ globals ++ aria-*`.
    pub order: &'static [&'static str],
    /// Categorias e/ou nomes de filho permitidos.
    pub children: &'static [&'static str],
    /// Filhos sem os quais o bloco não compila.
    pub required_children: &'static [&'static str],
    /// Filho que precisa vir primeiro (`""` = nenhum).
    pub first_child: &'static str,
    /// Exceções sobre `children`.
    pub forbidden_children: &'static [&'static str],
    /// Herda o content model do pai (`<a>`): `children` só vale na raiz.
    pub transparent: bool,
    /// Quem pode emitir o elemento.
    pub only: Option<Only>,
    /// Sem filhos e sem fechamento.
    pub void: bool,
    /// Espécie de nome acessível exigido.
    pub accessible_name: &'static str,
    /// Papéis ARIA aceitos (`role=`); vazio = `role` não existe no elemento.
    pub roles: &'static [&'static str],
    /// Invariantes que o elemento carrega (docs/04 §4.1).
    pub invariants: &'static [&'static str],
}

